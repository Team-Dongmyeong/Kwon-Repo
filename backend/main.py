class UserInput(BaseModel):
    sentence: str


@app.post("/predict")
async def predict(data: UserInput):
    # ── 1. 감정 분석 ─────────────────────────────────────
    inputs = tokenizer(data.sentence, return_tensors="pt", truncation=True, max_length=128)
    with torch.no_grad():
        outputs = emotion_model(**inputs)
    probs = torch.nn.functional.softmax(outputs.logits, dim=-1)
    pred_idx = torch.argmax(probs).item()
    emotion = emotion_labels[pred_idx]
    emotion_score = round(probs[0][pred_idx].item(), 4)

    # ── 2. 직무 유사도 분석 ───────────────────────────────
    query_emb = sbert_model.encode(data.sentence, convert_to_tensor=True)
    scores = {
        key: util.cos_sim(query_emb, emb).item()
        for key, emb in anchor_embeddings.items()
    }
    top3 = sorted(scores.items(), key=lambda x: -x[1])[:3]
    best_key, best_score = top3[0]

    return {
        "emotion": emotion,
        "emotion_score": emotion_score,
        "job_category": best_key[0],   # 중분류
        "job_type": best_key[1],        # 소분류
        "job_score": round(best_score, 4),
        "top3": [
            {"category": k[0], "type": k[1], "score": round(s, 4)}
            for k, s in top3
        ]
    }